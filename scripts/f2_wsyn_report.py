"""Render docs/results/f2_wsyn_calibration.{md,json} from runs/f2/*_v2.json (numbers by script, rule 11).

    env -u PYTHONPATH python scripts/f2_wsyn_report.py [--overwrite]
"""
import json
import sys
from pathlib import Path

import numpy as np
from scipy.stats import beta

ROOT = Path(__file__).resolve().parent.parent
R = ROOT / "runs" / "f2"
OUT = ROOT / "docs" / "results" / "f2_wsyn_calibration"


def cp(k, n, a=0.05):
    lo = 0.0 if k == 0 else beta.ppf(a / 2, k, n - k + 1)
    hi = 1.0 if k == n else beta.ppf(1 - a / 2, k + 1, n - k)
    return lo, hi


def main(argv=None):
    argv = sys.argv[1:] if argv is None else argv
    if (OUT.with_suffix(".md").exists() or OUT.with_suffix(".json").exists()) and "--overwrite" not in argv:
        raise SystemExit("output exists; use --overwrite")
    fw = json.loads((R / "flywire_v2.json").read_text())
    fs = json.loads((R / "flywire_search_v2.json").read_text())
    bn = json.loads((R / "banc_v2.json").read_text())
    K = json.loads((ROOT / "docs/results/f2_wsyn_k.json").read_text())
    out = dict(flywire_reference={}, variants={})
    # FlyWire gate-3 reference per drive
    for c in ("labellar", "leg"):
        r = [x for x in fw["runs"] if x["condition"] == c]
        out["flywire_reference"][c] = dict(
            n_driven=r[0]["n_driven"], network_rate_hz=float(np.mean([x["network_rate_hz"] for x in r])),
            nondriven_per_driven_grn=float(np.mean([x["nondriven_rate_hz_per_driven_grn"] for x in r])),
            mn9_rate_hz=float(np.mean([x["mn9_rate_hz"] for x in r])))
    L = ["# F2 prep: BANC `w_syn` calibration and sanity gates (prereg/03_banc_wsyn.md)", "",
         "Generated by `scripts/f2_wsyn_calibrate.py` (stages flywire, flywire_search, banc) + `scripts/f2_wsyn_report.py`; "
         "records `runs/f2/*_v2.json` (not committed). Open loop only: no F2 test and no behaviour was run. Criteria, "
         "seeds and windows are those of the committed pre-registration.", "",
         "**First run invalid, discarded (labelled).** The first calibration run (`runs/f2/invalid_v1_state_bug/`) used "
         "`set_weight_scale` after earlier runs; the engine then stored that run's dynamic state as the new initial state "
         "(no-input spikes, 20/20 ignitions in the reference arm). Engine fixed and a regression test added "
         "(`test_weight_scale_after_a_run_stores_the_pristine_state`); the same script and criteria were re-run (v2 "
         "records below). The same bug affected `match_weight_scale` (activity-matched control) whenever it was "
         "called after a run; no earlier reported result used it.", "",
         "## 1. Structural k (data only; `f2_wsyn_k.json`, `configs/banc_wsyn.yaml`)", "",
         f"k_global (A) = {K['as_run']['matched']['__all__']['k']:.3f}. Class k (A2, brain-neuropil view): "
         + ", ".join(f"{c} {K['as_run_brain_neuropils']['matched'][c]['k']:.2f}" for c in
                     ("sensory", "central", "optic", "visual_projection", "descending", "ascending", "motor")) + ".", ""]
    # variant B
    v = fw["validation"]
    L += ["## 2. Variant B: Shiu's criterion, operational definition and its validation", "",
          f"- FlyWire, s = 1 (`flywire_v2.json`): c = r(100) / max_f r(f) = {v['c']:.3f} "
          f"(r(100) = {v['r100']:.1f} Hz, r_max = {v['rmax']:.1f} Hz at the top of the grid); target 0.80.",
          f"- FlyWire bisection on [1, 12] (`flywire_search_v2.json`): c(1) = {fs['trace'][0]['c']:.3f}, "
          f"c(12) = {fs['trace'][1]['c']:.3f}; s_FlyWire = {fs['s_flywire']}. "
          f"**Validation {'passed' if fs['passes'] else 'FAILED'}**: the definition does not reproduce w_syn = 0.275 mV "
          "on FlyWire (c stays below 0.80 for every s in [1, 12]; MN9 saturates and then falls with s). Per section 4 "
          "of the pre-registration B is reported with this label and **not used**.",
          f"- BANC bisection (`banc_v2.json`): s_B = {bn['B_search']['s_B']:.3f} (bisection tolerance 2 %, seeds "
          f"{bn['B_search']['seeds']}); c is noisy between nearby s (2 seeds, 1 s each): "
          + "; ".join(f"s {t['s']:.2f}: c {t['c']:.2f}" for t in bn["B_search"]["trace"]) + ".", ""]
    # gates and run list
    L += ["## 3. Gates", "",
          "| variant | scale | gate 1: no-input spikes (seeds 0-4) | gate 2: ignited / 20 (95 % CI) | mean last-cut-step rate (Hz) "
          "| gate 3 labellar: G ratio (literal network-rate ratio) | gate 3 leg: G ratio (literal) | used |",
          "|---|---|---|---|---|---|---|---|"]
    fr = out["flywire_reference"]
    for name, vr in bn["variants"].items():
        g2 = vr["gate2_runs"]
        ign = vr["gate2_ignited"]
        lo, hi = cp(ign, len(g2))
        row = dict(gate1_pass=vr["gate1_pass"], gate2_ignited=ign, gate2_ci=[lo, hi],
                   last_cut_step_mean_hz=float(np.mean([r["last_cut_step_hz"] for r in g2])))
        cells = []
        g3_ok = True
        for cond, key in (("labellar", "labellar"), ("leg", "leg")):
            r = [x for x in vr["runs"] if x["condition"] == cond]
            G = float(np.mean([x["nondriven_rate_hz_per_driven_grn"] for x in r]))
            net = float(np.mean([x["network_rate_hz"] for x in r]))
            ratio, lit = G / fr[key]["nondriven_per_driven_grn"], net / fr[key]["network_rate_hz"]
            ok = 0.2 <= ratio <= 5.0
            g3_ok &= ok
            row[f"gate3_{cond}"] = dict(G=G, G_ratio=ratio, network_rate_hz=net, literal_ratio=lit, pass_=ok)
            cells.append(f"{ratio:.2f} ({lit:.2f}) {'pass' if ok else 'FAIL'}")
        row["gate3_pass"] = bool(g3_ok)
        used = vr["gate1_pass"] and vr["gate2_ignited"] == 0 and g3_ok and name != "B_wsyn_fit_mn9"
        row["used"] = bool(used)
        out["variants"][name] = row
        L.append(f"| {name} | {vr['state']:.3f} | {sum(vr['gate1_no_input_spikes_per_seed'])} "
                 f"| {ign} / {len(g2)} ({lo:.2f}-{hi:.2f}) | {row['last_cut_step_mean_hz']:.2f} | {cells[0]} | {cells[1]} | "
                 f"{'yes' if used else 'no'} |")
    L += ["", "FlyWire reference for gate 3 (same protocol, 100 Hz, 1 s, seeds 0-2): "
          + "; ".join(f"{c}: {fr[c]['n_driven']} driven GRNs, network {fr[c]['network_rate_hz']:.3f} Hz, MN9 "
                      f"{fr[c]['mn9_rate_hz']:.1f} Hz, non-driven rate per driven GRN {fr[c]['nondriven_per_driven_grn']:.5f} Hz"
                      for c in ("labellar", "leg")) + ".",
          "A variant that fails a gate is reported and not used (pre-registration section 5). B is additionally "
          "unused because its definition failed validation.", ""]
    # MN9 per side
    L += ["## 4. MN9 per side and network rate under sugar drive (100 Hz, 1 s, seeds 0-2; mean over seeds)", "",
          "| variant | drive | MN9 " + bn["variants"]["R"]["mn9_sides"][0] + " (Hz) | MN9 " + bn["variants"]["R"]["mn9_sides"][1]
          + " (Hz) | MN9 mean (Hz) | network (Hz) | non-driven network (Hz) |", "|---|---|---|---|---|---|---|"]
    for name, vr in bn["variants"].items():
        for cond in ("labellar", "leg", "labellar_left", "labellar_right"):
            r = [x for x in vr["runs"] if x["condition"] == cond]
            m = np.mean([x["mn9_rate_hz_per_neuron"] for x in r], axis=0)
            L.append(f"| {name} | {cond} | {m[0]:.1f} | {m[1]:.1f} | {np.mean([x['mn9_rate_hz'] for x in r]):.1f} | "
                     f"{np.mean([x['network_rate_hz'] for x in r]):.3f} | "
                     f"{np.mean([x['nondriven_rate_hz'] for x in r]):.3f} |")
            out["variants"][name].setdefault("mn9_by_condition", {})[cond] = dict(
                per_neuron=m.tolist(), sides=vr["mn9_sides"], network_rate_hz=float(np.mean([x["network_rate_hz"] for x in r])))
    used = [n for n, r in out["variants"].items() if r["used"]]
    ign = {n: r["gate2_ignited"] for n, r in out["variants"].items()}
    L += ["", "## 5. Result", "",
          f"- Variants used downstream (all gates passed, definition validated): **{', '.join(used) if used else 'none'}**.",
          f"- Gate 2 (ignition after the cut, 20 seeds): " + ", ".join(f"{n} {k}/20" for n, k in ign.items()) + ". "
          "Every scaled variant keeps firing after the input is cut (last cut step "
          + ", ".join(f"{n} {r['last_cut_step_mean_hz']:.1f} Hz" for n, r in out["variants"].items() if n != "R")
          + "), and its network rate under sugar drive is far above the FlyWire rate: the scale at which MN9 responds "
          "(B: s = " + f"{bn['B_search']['s_B']:.2f}" + ") is already in the self-sustaining regime of the BANC graph.",
          "- The reference arm passes gates 1 and 2 but is silent at MN9 and lies below the lower bound of gate 3.",
          "- Any further route (input normalisation, a different scale per region, an inhibition scale) needs a new "
          "pre-registration; none was tried here.", "",
          f"BANC stage: {bn['n_neurons']:,} neurons; peak RAM {bn['peak_rss_gb']:.2f} GB; wall {bn['total_wall_s']:.0f} s "
          f"(bisection included). FlyWire reference stage: peak RAM {fw['peak_rss_gb']:.2f} GB, wall {fw['total_wall_s']:.0f} s.", ""]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.with_suffix(".json").write_text(json.dumps(out, indent=1))
    OUT.with_suffix(".md").write_text("\n".join(L))
    print("\n".join(L))


if __name__ == "__main__":
    raise SystemExit(main())

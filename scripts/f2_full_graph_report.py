"""Render docs/results/f2_full_graph.{md,json} from runs/f2/banc888_full_*.json (numbers by script, rule 11).

    env -u PYTHONPATH python scripts/f2_full_graph_report.py [--overwrite]
"""
import json
import sys
from pathlib import Path

import numpy as np
from scipy.stats import beta

ROOT = Path(__file__).resolve().parent.parent
R = ROOT / "runs" / "f2"
OUT = ROOT / "docs" / "results" / "f2_full_graph"
RESPONSE_FRACTION = 0.10       # prereg/04 section 4
CONDS = ("labellar", "leg", "labellar_left", "labellar_right")


def cp(k, n, a=0.05):
    lo = 0.0 if k == 0 else beta.ppf(a / 2, k, n - k + 1)
    hi = 1.0 if k == n else beta.ppf(1 - a / 2, k + 1, n - k)
    return lo, hi


def main(argv=None):
    argv = sys.argv[1:] if argv is None else argv
    if (OUT.with_suffix(".md").exists() or OUT.with_suffix(".json").exists()) and "--overwrite" not in argv:
        raise SystemExit("output exists; use --overwrite")
    fw = json.loads((R / "flywire_v2.json").read_text())
    fr = {}
    for c in ("labellar", "leg"):
        r = [x for x in fw["runs"] if x["condition"] == c]
        fr[c] = dict(n_driven=r[0]["n_driven"], network=float(np.mean([x["network_rate_hz"] for x in r])),
                     G=float(np.mean([x["nondriven_rate_hz_per_driven_grn"] for x in r])),
                     mn9=float(np.mean([x["mn9_rate_hz"] for x in r])))
    out = dict(flywire_reference=fr, sets={})
    L = ["# F2 prep: reference arm on the full BANC v888 graph (prereg/04_banc_full_graph.md)", "",
         "Generated by `scripts/f2_full_graph_run.py` + `scripts/f2_full_graph_report.py`; records "
         "`runs/f2/banc888_full_*.json` (not committed). Shiu parameters unchanged (scale 1.0), reference sign rule, "
         "no scaling variant, no F2 test. Graph QA (data only): `docs/results/f2_full_graph_qa.md`.", ""]
    for ns in ("codex", "all"):
        p = R / f"banc888_full_{ns}.json"
        if not p.exists():
            continue
        d = json.loads(p.read_text())
        v = d["variants"]["R"]
        g2 = v["gate2_runs"]
        lo, hi = cp(v["gate2_ignited"], len(g2))
        o = dict(neurons=d["n_neurons"], pairs=d["pairs"], synapses=d["synapses"],
                 gate1_pass=v["gate1_pass"], gate2_ignited=v["gate2_ignited"], gate2_ci=[lo, hi],
                 last_cut_step_mean_hz=float(np.mean([r["last_cut_step_hz"] for r in g2])),
                 peak_rss_gb=d["peak_rss_gb"], total_wall_s=d["total_wall_s"], mn9_symmetry=d["mn9_symmetry"])
        g3_ok, cells = True, {}
        for c in ("labellar", "leg"):
            r = [x for x in v["runs"] if x["condition"] == c]
            G, net = (float(np.mean([x[k] for x in r])) for k in ("nondriven_rate_hz_per_driven_grn", "network_rate_hz"))
            ratio, lit = G / fr[c]["G"], net / fr[c]["network"]
            ok = 0.2 <= ratio <= 5.0
            g3_ok &= ok
            o[f"gate3_{c}"] = dict(G=G, G_ratio=ratio, network_rate_hz=net, literal_ratio=lit, pass_=ok)
            cells[c] = f"{ratio:.2f} ({lit:.2f}) {'pass' if ok else 'FAIL'}"
        o["gate3_pass"] = bool(g3_ok)
        rl = [x["mn9_rate_hz"] for x in v["runs"] if x["condition"] == "labellar"]
        o["mn9_labellar_mean_hz"] = float(np.mean(rl))
        o["mn9_responds"] = bool(np.mean(rl) >= RESPONSE_FRACTION * fr["labellar"]["mn9"])
        o["gates_pass"] = bool(v["gate1_pass"] and v["gate2_ignited"] == 0 and g3_ok)
        o["by_condition"] = {}
        out["sets"][ns] = o
        title = "primary: 158,262 Codex neurons" if ns == "codex" else "sensitivity: all 188,508 v888 meta rows"
        sym = d["mn9_symmetry"][0] if d["mn9_symmetry"] else None
        L += [f"## {title}", "",
              f"- Graph: {d['n_neurons']:,} neurons, {d['pairs']:,} pairs, {d['synapses']:,} synapses (no threshold); "
              f"peak RAM {d['peak_rss_gb']:.2f} GB, wall {d['total_wall_s']:.0f} s.",
              f"- Gate 1 (no input, seeds 0-4): {sum(v['gate1_no_input_spikes_per_seed'])} spikes -> "
              f"{'pass' if v['gate1_pass'] else 'FAIL'}.",
              f"- Gate 2 (ignition after the cut, 20 seeds): {v['gate2_ignited']} / {len(g2)} ignited "
              f"(95 % CI {lo:.2f}-{hi:.2f}), mean last-cut-step rate {o['last_cut_step_mean_hz']:.3f} Hz -> "
              f"{'pass' if v['gate2_ignited'] == 0 else 'FAIL'}.",
              f"- Gate 3 (non-driven rate per driven GRN vs FlyWire, literal network-rate ratio in brackets): "
              f"labellar {cells['labellar']}; leg {cells['leg']}.",
              f"- FlyWire reference (same protocol): labellar network {fr['labellar']['network']:.3f} Hz, MN9 "
              f"{fr['labellar']['mn9']:.1f} Hz; leg network {fr['leg']['network']:.3f} Hz, MN9 {fr['leg']['mn9']:.1f} Hz.",
              (f"- MN9 symmetry gate on this graph: input synapses L {sym['in_left']:.0f} / R {sym['in_right']:.0f}, "
               f"log2(R/L) = {sym['log2_total']:.2f} -> {'pass' if sym['pass'] else 'FAIL'}." if sym else
               "- MN9 symmetry gate: type not found."),
              "", "| drive | MN9 " + v["mn9_sides"][0] + " (Hz) | MN9 " + v["mn9_sides"][1]
              + " (Hz) | MN9 mean (Hz) | network (Hz) | non-driven (Hz) |", "|---|---|---|---|---|---|"]
        for c in CONDS:
            r = [x for x in v["runs"] if x["condition"] == c]
            m = np.mean([x["mn9_rate_hz_per_neuron"] for x in r], axis=0)
            net = float(np.mean([x["network_rate_hz"] for x in r]))
            o["by_condition"][c] = dict(per_neuron=m.tolist(), sides=v["mn9_sides"], network_rate_hz=net,
                                        mn9_mean_hz=float(np.mean([x["mn9_rate_hz"] for x in r])))
            L.append(f"| {c} | {m[0]:.1f} | {m[1]:.1f} | {np.mean([x['mn9_rate_hz'] for x in r]):.1f} | {net:.3f} | "
                     f"{np.mean([x['nondriven_rate_hz'] for x in r]):.3f} |")
        L += ["", f"- **MN9 responds** (labellar mean {o['mn9_labellar_mean_hz']:.1f} Hz >= "
              f"{RESPONSE_FRACTION:.0%} of FlyWire's {fr['labellar']['mn9']:.1f} Hz): "
              f"**{'yes' if o['mn9_responds'] else 'no'}**; all gates pass: **{'yes' if o['gates_pass'] else 'no'}**.", ""]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.with_suffix(".json").write_text(json.dumps(out, indent=1))
    OUT.with_suffix(".md").write_text("\n".join(L))
    print("\n".join(L))


if __name__ == "__main__":
    raise SystemExit(main())

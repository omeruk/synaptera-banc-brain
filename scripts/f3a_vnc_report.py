"""Render docs/results/f3a_banc_vnc.{md,json} from runs/f3a/f3a_v3.json (numbers by script, rule 11).

    env -u PYTHONPATH python scripts/f3a_vnc_report.py [--run runs/f3a/f3a_v3.json] [--overwrite]
"""
import argparse
import json
from pathlib import Path

import numpy as np
from scipy.stats import beta

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "results" / "f3a_banc_vnc"
DRIVES = ["G20", "G50", "G100", "GL100", "GR100", "AL100", "AR100", "F100"]
RUNAWAY_HZ, MIN_HZ, STEER_HZ, A_HZ, TTMN_HZ = 5.0, 1.0, 1.0, 5.0, 5.0


def cp(k, n, a=0.05):
    lo = 0.0 if k == 0 else beta.ppf(a / 2, k, n - k + 1)
    hi = 1.0 if k == n else beta.ppf(1 - a / 2, k + 1, n - k)
    return float(lo), float(hi)


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--run", default=str(ROOT / "runs/f3a/f3a_v3.json"))
    ap.add_argument("--overwrite", action="store_true")
    a = ap.parse_args(argv)
    if (OUT.with_suffix(".md").exists() or OUT.with_suffix(".json").exists()) and not a.overwrite:
        raise SystemExit("output exists; use --overwrite")
    R = json.loads(Path(a.run).read_text())
    runs = R["runs"]
    T, SYM = R["types"], R["symmetry"]

    def sel(d):
        return [r for r in runs if r["drive"] == d]

    def rate(t, s, d):
        r = [x["rate_hz"].get(f"{t}|{s}") for x in sel(d)]
        return None if r[0] is None else (float(np.mean(r)), float(np.std(r)))

    def both(t, d):
        nl, nr = T[t]["n_left"], T[t]["n_right"]
        per_seed = []
        for x in sel(d):
            v = [(x["rate_hz"].get(f"{t}|{s}"), n) for s, n in (("left", nl), ("right", nr)) if n]
            per_seed.append(sum(r * n for r, n in v) / sum(n for _, n in v))
        return float(np.mean(per_seed))

    def sym_cell(t):
        s = SYM.get(t)
        if s is None:
            return "not testable"
        return f"{'pass' if s['passed'] else 'FAIL'} ({s['log2_total']:+.2f})"

    out = dict(graph=dict(n_neurons=R["n_neurons"], pairs=R["pairs"], synapses=R["synapses"],
                          data_source=R["graph_meta"].get("data_source")), dn_groups=R["dn_groups"])
    L = ["# F3a: BANC VNC open loop, DN -> motor neurons (prereg/06_banc_vnc_dn_to_mn.md)", "",
         "Generated by `scripts/f3a_vnc_run.py` + `scripts/f3a_vnc_report.py`; record `runs/f3a/f3a_v3.json` (not committed). "
         "Open loop, BANC VNC only: Poisson drive on DN types, no brain, no body, no F2 test. Protocol, neuron sets, gates "
         "and expectations are those of the committed pre-registration.", "",
         "## 1. Graph and driven groups", "",
         f"- `{out['graph']['data_source']}`: {R['n_neurons']:,} neurons, {R['pairs']:,} pairs, {R['synapses']:,} synapses; "
         f"reference arm (w_syn 0.275 mV, scale 1.0); peak RAM {R['peak_rss_gb']:.2f} GB, wall {R['total_wall_s']:.0f} s.",
         "- DN groups (neurons): " + ", ".join(f"{k} {v}" for k, v in R["dn_groups"].items()) + ".", ""]
    # gates
    g1 = sum(r["total_spikes"] for r in sel("D0") if r["seed"] in R["seeds"]["gate1"])
    g1_all = sum(r["total_spikes"] for r in sel("D0"))
    g2 = R["gate2_runs"]
    ign = sum(r["ignited"] for r in g2)
    lo, hi = cp(ign, len(g2))
    maxnet = {d: float(np.mean([x["network_rate_hz"] for x in sel(d)])) for d in DRIVES}
    g3 = max(maxnet.values()) < RUNAWAY_HZ
    gates = dict(gate1_spikes_seeds0_4=int(g1), gate1_spikes_all_seeds=int(g1_all), gate1_pass=bool(g1 == 0),
                 gate2_ignited=int(ign), gate2_n=len(g2), gate2_ci=[lo, hi], gate2_pass=bool(ign == 0),
                 gate2_mean_last_cut_step_hz=float(np.mean([r["last_cut_step_hz"] for r in g2])),
                 gate3_max_network_rate_hz=max(maxnet.values()), gate3_pass=bool(g3))
    out["gates"] = gates
    L += ["## 2. Gates", "",
          "| gate | result | pass |", "|---|---|---|",
          f"| 1: no input, seeds 0-4 (spikes) | {g1} (seeds 0-9: {g1_all}) | {'pass' if gates['gate1_pass'] else 'FAIL'} |",
          f"| 2: ignition after the 200 ms cut, all DN groups 100 Hz, 50 seeds | {ign} / {len(g2)} (95 % CI {lo:.3f}-{hi:.3f}); "
          f"mean last-cut-step rate {gates['gate2_mean_last_cut_step_hz']:.3f} Hz | {'pass' if gates['gate2_pass'] else 'FAIL'} |",
          f"| 3': network rate under drive < {RUNAWAY_HZ:g} Hz in every drive | max {gates['gate3_max_network_rate_hz']:.3f} Hz "
          f"({max(maxnet, key=maxnet.get)}) | {'pass' if g3 else 'FAIL'} |", ""]
    # drive summary
    L += ["## 3. Drives: network, driven DNs and activity after the cut (10 seeds, mean)", "",
          "| drive | driven DN rate (Hz) | network (Hz) | non-driven (Hz) | cut mean (Hz) | last cut step (Hz) |",
          "|---|---|---|---|---|---|"]
    out["drives"] = {}
    for d in ["D0"] + DRIVES:
        rr = sel(d)
        m = lambda k: float(np.mean([x[k] for x in rr]))  # noqa: E731
        dn = m("driven_dn_rate_hz") if rr[0]["driven_dn_rate_hz"] is not None else None
        out["drives"][d] = dict(driven_dn_rate_hz=dn, network_rate_hz=m("network_rate_hz"),
                                nondriven_rate_hz=m("nondriven_rate_hz"), cut_mean_hz=m("cut_mean_hz"),
                                cut_last_step_hz=m("cut_last_step_hz"))
        L.append(f"| {d} | {'-' if dn is None else f'{dn:.1f}'} | {m('network_rate_hz'):.4f} | {m('nondriven_rate_hz'):.4f} "
                 f"| {m('cut_mean_hz'):.4f} | {m('cut_last_step_hz'):.4f} |")
    # MN table
    L += ["", "## 4. Motor-neuron rate per type, left / right (Hz, mean over 10 seeds; 1 s drive window)", "",
          "Symmetry gate: input synapses, total and excitatory, |log2(R/L)| < 0.5 (value shown is log2 total R/L); a left/right "
          "reading of a type that fails the gate is not used.", "",
          "| category | type | n L/R | symmetry gate | " + " | ".join(f"{d} L/R" for d in DRIVES) + " |",
          "|---|---|---|---|" + "---|" * len(DRIVES)]
    out["rates"] = {}
    order = ["wing", "wing_steering", "other_wing", "TTMn", "haltere", "neck"]
    for cat in order:
        for t in [t for t, v in T.items() if v["category"] == cat]:
            cells, rec = [], {}
            for d in DRIVES:
                l, r = rate(t, "left", d), rate(t, "right", d)
                rec[d] = dict(left=l, right=r)
                cells.append(f"{'-' if l is None else f'{l[0]:.1f}'} / {'-' if r is None else f'{r[0]:.1f}'}")
            out["rates"][t] = dict(category=cat, n_left=T[t]["n_left"], n_right=T[t]["n_right"],
                                   symmetry=SYM.get(t), by_drive=rec)
            L.append(f"| {cat} | {t} | {T[t]['n_left']}/{T[t]['n_right']} | {sym_cell(t)} | " + " | ".join(cells) + " |")
    # expectations
    wing = [t for t, v in T.items() if v["category"] in ("wing", "wing_steering")]
    ea = []
    for t in wing:
        r20, r50, r100 = (both(t, d) for d in ("G20", "G50", "G100"))
        ea.append(dict(type=t, g20=r20, g50=r50, g100=r100, ge5=bool(r100 >= A_HZ), monotone=bool(r20 < r50 < r100)))
    a_hit = any(e["ge5"] and e["monotone"] for e in ea)
    out["expectation_a"] = dict(hit=bool(a_hit), types=ea)
    eb, b_not = [], []
    for t in wing:
        s = SYM.get(t)
        if s is None or not s["passed"]:
            continue
        l, r = rate(t, "left", "G100")[0], rate(t, "right", "G100")[0]
        if (l + r) / 2 < MIN_HZ:
            b_not.append(t)
            continue
        lg = float(np.log2(r / l)) if l > 0 and r > 0 else float("inf")
        eb.append(dict(type=t, left=l, right=r, log2_rl=lg, ok=bool(abs(lg) < 0.5)))
    b_hit = bool(eb) and all(e["ok"] for e in eb)
    out["expectation_b"] = dict(hit=b_hit, evaluated=eb, not_evaluated=b_not,
                                n_pass_gate=int(sum(1 for t in wing if SYM.get(t, {}).get("passed"))))
    ec = []
    for t in [t for t, v in T.items() if v["category"] == "wing_steering"]:
        dl = rate(t, "left", "AL100")[0] - rate(t, "right", "AL100")[0]
        dr = rate(t, "left", "AR100")[0] - rate(t, "right", "AR100")[0]
        ec.append(dict(type=t, D_AL100=float(dl), D_AR100=float(dr), both=bool(abs(dl) >= STEER_HZ and abs(dr) >= STEER_HZ),
                       sign_AL100="ipsi>contra" if dl > 0 else "contra>ipsi" if dl < 0 else "equal",
                       sign_AR100="ipsi>contra" if dr < 0 else "contra>ipsi" if dr > 0 else "equal"))
    c_hit = any(e["both"] for e in ec)
    out["expectation_c"] = dict(hit=bool(c_hit), types=ec)
    ttm = both("TTMn", "F100")
    dlm = {t: both(t, "F100") for t in wing if t.startswith(("DLM", "DVM"))}
    d_fail = ttm < TTMN_HZ
    syn = R["direct_synapses"]
    out["expectation_d"] = dict(ttmn_mean_hz=ttm, ttmn_below_5=bool(d_fail), dlm_dvm_f100_hz=dlm,
                                direct_synapses_gf_to_ttmn=syn["GF"]["TTMn"],
                                direct_synapses_gf_to_dlm_dvm=int(sum(v for k, v in syn["GF"].items() if k.startswith(("DLM", "DVM")))))
    decision = bool(a_hit and gates["gate1_pass"] and gates["gate2_pass"] and gates["gate3_pass"])
    out["decision"] = dict(usable=decision)
    L += ["", "## 5. Pre-registered expectations", "",
          f"- **(a) bilateral DNg02 drive: a wing-MN type >= {A_HZ:g} Hz at G100 and increasing with the rate: "
          f"{'HIT' if a_hit else 'MISS'}.** Types (mean of both sides): " + "; ".join(
              f"{e['type']} {e['g20']:.1f} / {e['g50']:.1f} / {e['g100']:.1f} Hz" for e in ea if e["g100"] > 0.05 or e["g50"] > 0.05)
          + ("" if any(e["g100"] > 0.05 or e["g50"] > 0.05 for e in ea) else "all wing types silent at 20/50/100 Hz") + ".",
          f"- **(b) symmetric drive, |log2(R/L)| < 0.5 in the wing-MN types that pass the gate: "
          f"{'HIT' if b_hit else 'MISS' if eb else 'NOT EVALUATED (no type with both-side mean rate >= 1 Hz that passes the gate)'}.** "
          f"{out['expectation_b']['n_pass_gate']} wing types pass the symmetry gate; evaluated: "
          + (", ".join(f"{e['type']} R/L {e['right']:.1f}/{e['left']:.1f} ({e['log2_rl']:+.2f})" for e in eb) or "none")
          + ".",
          f"- **(c) unilateral DNa02: |left - right| >= {STEER_HZ:g} Hz in a steering type under both drives: "
          f"{'HIT' if c_hit else 'MISS'}.** Per steering type (D under AL100 / AR100, Hz; sign): "
          + "; ".join(f"{e['type']} {e['D_AL100']:+.1f} / {e['D_AR100']:+.1f} ({e['sign_AL100']}, {e['sign_AR100']})"
                      for e in ec if abs(e["D_AL100"]) > 0.05 or abs(e["D_AR100"]) > 0.05) + ".",
          f"- **(d) GF -> TTMn: TTMn {ttm:.1f} Hz at F100 ({'below' if d_fail else 'at or above'} {TTMN_HZ:g} Hz; expectation "
          f"'may fail' {'met' if d_fail else 'not met'}).** DLM/DVM at F100: "
          + ", ".join(f"{t} {v:.1f}" for t, v in dlm.items()) + f". Direct synapses GF -> TTMn "
          f"{out['expectation_d']['direct_synapses_gf_to_ttmn']}, GF -> DLM/DVM {out['expectation_d']['direct_synapses_gf_to_dlm_dvm']}.",
          "", "## 6. Decision (prereg section 7)", "",
          f"- (a) {'holds' if a_hit else 'does not hold'}; gates 1, 2, 3': {gates['gate1_pass']}, {gates['gate2_pass']}, {g3}.",
          f"- **{'The BANC v3 VNC is usable for the hybrid.' if decision else 'Not usable under the registered rule: stop and report.'}**",
          "- Direct DN -> MN synapse counts for every DN group and readout type are in `f3a_banc_vnc.json`.", ""]
    # post-hoc observations (not registered; computed from the same record)
    g100 = sel("G100")
    ph = dict(g100_cut_mean_hz=[x["cut_mean_hz"] for x in g100], g100_network_hz=[x["network_rate_hz"] for x in g100],
              g100_cut_over_drive=float(np.mean([x["cut_mean_hz"] for x in g100]) / np.mean([x["network_rate_hz"] for x in g100])),
              gate2_last_cut_step_hz_range=[float(min(r["last_cut_step_hz"] for r in g2)),
                                            float(max(r["last_cut_step_hz"] for r in g2))],
              one_sided={})
    for e in eb:
        if not e["ok"]:
            t = e["type"]
            hi_s, lo_s = ("right", "left") if e["right"] > e["left"] else ("left", "right")
            ph["one_sided"][t] = dict(active_side=hi_s, seeds_active_side_gt0=int(sum(x["rate_hz"][f"{t}|{hi_s}"] > 0 for x in g100)),
                                      seeds_other_side_gt0=int(sum(x["rate_hz"][f"{t}|{lo_s}"] > 0 for x in g100)), n_seeds=len(g100))
    out["post_hoc"] = ph
    L += ["## 7. Post-hoc observations (not registered; same record)", "",
          f"- **Activity persists through the cut at G100.** Network rate during drive {np.mean(ph['g100_network_hz']):.3f} Hz, "
          f"mean over the 200 ms cut {np.mean(ph['g100_cut_mean_hz']):.3f} Hz (ratio {ph['g100_cut_over_drive']:.2f}); in the 50 "
          f"gate-2 runs the last cut step is {ph['gate2_last_cut_step_hz_range'][0]:.2f}-{ph['gate2_last_cut_step_hz_range'][1]:.2f} Hz. "
          f"This is below the registered ignition threshold (1 Hz), so gate 2 passes, but it does not decay within 200 ms. "
          "Which neurons carry it, and for how long, was not recorded.",
          "- **Lateralised wing-MN response under symmetric drive (expectation b missed):** " + ("; ".join(
              f"{t}: {v['active_side']} side active in {v['seeds_active_side_gt0']}/{v['n_seeds']} seeds, other side in "
              f"{v['seeds_other_side_gt0']}/{v['n_seeds']}" for t, v in ph["one_sided"].items()) or "none") + ". "
          f"DNg02 neurons driven: {R['dn_groups']['DNg02_L']} left, {R['dn_groups']['DNg02_R']} right (the `DNg02_d` and "
          "`DNg02_h` subtypes are right-sided only in the Codex table).", ""]
    out["direct_synapses"] = syn
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.with_suffix(".json").write_text(json.dumps(out, indent=1))
    OUT.with_suffix(".md").write_text("\n".join(L))
    print("\n".join(L))


if __name__ == "__main__":
    raise SystemExit(main())

"""Render docs/results/f2_innorm.{md,json} from runs/f2/{r3_v3,n_v2,n_v3}.json (numbers by script, rule 11).

    env -u PYTHONPATH python scripts/f2_innorm_report.py [--overwrite]

Tables as in ``f2_full_graph.md`` (prereg/05 sections 3-5), per arm; the decision of prereg/05 section 5 is evaluated
here from the records, not typed.
"""
import json
import sys
from pathlib import Path

import numpy as np
from scipy.stats import beta

ROOT = Path(__file__).resolve().parent.parent
R = ROOT / "runs" / "f2"
OUT = ROOT / "docs" / "results" / "f2_innorm"
RESPONSE_FRACTION = 0.10       # prereg/05 section 4
CONDS = ("labellar", "leg", "labellar_left", "labellar_right")
ARMS = (("R3", "r3_v3.json", "banc888_full_v3"), ("N_v2", "n_v2.json", "banc888_full_v2"),
        ("N_v3", "n_v3.json", "banc888_full_v3"))
PREFERENCE = ("R3", "N_v2", "N_v3")
TITLES = {"R3": "Arm R3: reference arm (Shiu unchanged) on the v3 full graph",
          "N_v2": "Arm N (`innorm_homolog`) on the v2 full graph (primary)",
          "N_v3": "Arm N (`innorm_homolog`) on the v3 full graph (secondary)"}


def cp(k, n, a=0.05):
    lo = 0.0 if k == 0 else beta.ppf(a / 2, k, n - k + 1)
    hi = 1.0 if k == n else beta.ppf(1 - a / 2, k + 1, n - k)
    return lo, hi


def sem(x):
    x = np.asarray(x, float)
    return float(x.std(ddof=1) / np.sqrt(len(x))) if len(x) > 1 else float("nan")


def main(argv=None):
    argv = sys.argv[1:] if argv is None else argv
    if (OUT.with_suffix(".md").exists() or OUT.with_suffix(".json").exists()) and "--overwrite" not in argv:
        raise SystemExit("output exists; use --overwrite")
    fw = json.loads((R / "flywire_v2.json").read_text())
    qa = json.loads((ROOT / "docs/results/f2_v3_qa.json").read_text())
    fr = {}
    for c in ("labellar", "leg"):
        r = [x for x in fw["runs"] if x["condition"] == c]
        fr[c] = dict(n_driven=r[0]["n_driven"], network=float(np.mean([x["network_rate_hz"] for x in r])),
                     G=float(np.mean([x["nondriven_rate_hz_per_driven_grn"] for x in r])),
                     mn9=float(np.mean([x["mn9_rate_hz"] for x in r])))
    out = dict(flywire_reference=fr, arms={}, response_threshold_hz=RESPONSE_FRACTION * fr["labellar"]["mn9"])
    L = ["# F2 prep: v3 graph and per-neuron input normalisation (prereg/05_banc_v3_and_innorm.md)", "",
         "Generated by `scripts/f2_innorm_run.py` + `scripts/f2_innorm_report.py`; records `runs/f2/{r3_v3,n_v2,n_v3}.json` "
         "(not committed). Open loop only: no F2 test was run. Gate 1 seeds 0-4, gate 2 seeds 200-249, gate 3 and "
         "readouts seeds 0-9. Data-only QA: `docs/results/f2_v3_qa.md`. FlyWire reference (`runs/f2/flywire_v2.json`, "
         "seeds 0-2): "
         + "; ".join(f"{c}: network {fr[c]['network']:.3f} Hz, MN9 {fr[c]['mn9']:.1f} Hz, non-driven per driven GRN "
                     f"{fr[c]['G']:.5f} Hz" for c in ("labellar", "leg"))
         + f". MN9 responds = labellar MN9 >= {out['response_threshold_hz']:.2f} Hz.", ""]
    summary = ["| arm | graph | gate 1 | gate 2 ignited (95 % CI) | gate 3 labellar / leg | MN9 labellar (Hz) | MN9 "
               "responds | candidate |", "|---|---|---|---|---|---|---|---|"]
    for arm, fn, gname in ARMS:
        p = R / fn
        if not p.exists():
            continue
        d = json.loads(p.read_text())
        v = d["variants"][arm]
        g2 = v["gate2_runs"]
        lo, hi = cp(v["gate2_ignited"], len(g2))
        o = dict(graph=gname, neurons=d["n_neurons"], pairs=d["pairs"], synapses=d["synapses"],
                 gate1_pass=v["gate1_pass"], gate2_ignited=v["gate2_ignited"], gate2_n=len(g2), gate2_ci=[lo, hi],
                 last_cut_step_mean_hz=float(np.mean([r["last_cut_step_hz"] for r in g2])),
                 peak_rss_gb=d["peak_rss_gb"], total_wall_s=d["total_wall_s"], mn9_symmetry=d["mn9_symmetry"])
        g3_ok, cells = True, {}
        for c in ("labellar", "leg"):
            r = [x for x in v["runs"] if x["condition"] == c]
            G, net = (float(np.mean([x[k] for x in r])) for k in ("nondriven_rate_hz_per_driven_grn", "network_rate_hz"))
            ratio, lit = G / fr[c]["G"], net / fr[c]["network"]
            ok = 0.2 <= ratio <= 5.0
            g3_ok &= ok
            o[f"gate3_{c}"] = dict(G=G, G_ratio=ratio, network_rate_hz=net, literal_ratio=lit, pass_=ok, n_seeds=len(r))
            cells[c] = f"{ratio:.2f} ({lit:.2f}) {'pass' if ok else 'FAIL'}"
        o["gate3_pass"] = bool(g3_ok)
        rl = [x["mn9_rate_hz"] for x in v["runs"] if x["condition"] == "labellar"]
        o["mn9_labellar_mean_hz"], o["mn9_labellar_sem_hz"] = float(np.mean(rl)), sem(rl)
        o["mn9_responds"] = bool(np.mean(rl) >= out["response_threshold_hz"])
        o["gates_pass"] = bool(v["gate1_pass"] and v["gate2_ignited"] == 0 and g3_ok)
        o["candidate"] = bool(o["gates_pass"] and o["mn9_responds"])
        o["by_condition"] = {}
        al = qa["antennal_lobe"][gname]
        o["antennal_lobe"] = al["innorm"] if arm.startswith("N") else al["unscaled"]
        out["arms"][arm] = o
        sym = d["mn9_symmetry"][0] if d["mn9_symmetry"] else None
        L += [f"## {TITLES[arm]}", "",
              f"- Graph: `{gname}` primary set, {d['n_neurons']:,} neurons, {d['pairs']:,} pairs, {d['synapses']:,} "
              f"synapses (no threshold); peak RAM {d['peak_rss_gb']:.2f} GB, wall {d['total_wall_s']:.0f} s; "
              f"weights SHA-256 `{v['weights_sha256'][:16]}…`"
              + (f", per-post factors `{v['post_scale_sha256'][:16]}…`" if v.get("post_scale_sha256") else "") + ".",
              f"- Gate 1 (no input, seeds 0-4): {sum(v['gate1_no_input_spikes_per_seed'])} spikes -> "
              f"{'pass' if v['gate1_pass'] else 'FAIL'}.",
              f"- Gate 2 (ignition after the cut, {len(g2)} seeds): {v['gate2_ignited']} / {len(g2)} ignited "
              f"(95 % CI {lo:.3f}-{hi:.3f}), mean last-cut-step rate {o['last_cut_step_mean_hz']:.3f} Hz -> "
              f"{'pass' if v['gate2_ignited'] == 0 else 'FAIL'}.",
              f"- Gate 3 (non-driven rate per driven GRN vs FlyWire, 10 seeds; literal network-rate ratio in "
              f"brackets): labellar {cells['labellar']}; leg {cells['leg']}.",
              (f"- MN9 symmetry gate on this graph (unscaled counts): input synapses L {sym['in_left']:.0f} / R "
               f"{sym['in_right']:.0f}, log2(R/L) = {sym['log2_total']:.2f} -> {'pass' if sym['pass'] else 'FAIL'}."
               if sym else "- MN9 symmetry gate: type not found."),
              f"- Antennal-lobe leading eigenvalue (signed / excitatory-only): {o['antennal_lobe']['leading_eig_signed_syn']:,.0f}"
              f" / {o['antennal_lobe']['leading_eig_exc_syn']:,.0f} (FlyWire "
              f"{qa['antennal_lobe']['flywire']['leading_eig_signed_syn']:,.0f} / "
              f"{qa['antennal_lobe']['flywire']['leading_eig_exc_syn']:,.0f}).",
              "", "| drive | MN9 " + v["mn9_sides"][0] + " (Hz) | MN9 " + v["mn9_sides"][1]
              + " (Hz) | MN9 mean (Hz) | MN9 s.e. over seeds | network (Hz) | non-driven (Hz) |",
              "|---|---|---|---|---|---|---|"]
        for c in CONDS:
            r = [x for x in v["runs"] if x["condition"] == c]
            m = np.mean([x["mn9_rate_hz_per_neuron"] for x in r], axis=0)
            net = float(np.mean([x["network_rate_hz"] for x in r]))
            o["by_condition"][c] = dict(per_neuron=m.tolist(), sides=v["mn9_sides"], network_rate_hz=net,
                                        mn9_mean_hz=float(np.mean([x["mn9_rate_hz"] for x in r])),
                                        mn9_sem_hz=sem([x["mn9_rate_hz"] for x in r]))
            L.append(f"| {c} | {m[0]:.1f} | {m[1]:.1f} | {np.mean([x['mn9_rate_hz'] for x in r]):.1f} | "
                     f"{sem([x['mn9_rate_hz'] for x in r]):.2f} | {net:.3f} | "
                     f"{np.mean([x['nondriven_rate_hz'] for x in r]):.3f} |")
        L += ["", f"- **MN9 responds** (labellar mean {o['mn9_labellar_mean_hz']:.1f} Hz >= "
              f"{out['response_threshold_hz']:.2f} Hz): **{'yes' if o['mn9_responds'] else 'no'}**; gates 1-3 pass: "
              f"**{'yes' if o['gates_pass'] else 'no'}**; candidate: **{'yes' if o['candidate'] else 'no'}**.", ""]
        summary.append(f"| {arm} | {gname} | {'pass' if v['gate1_pass'] else 'FAIL'} | {v['gate2_ignited']} / {len(g2)} "
                       f"({lo:.2f}-{hi:.2f}) | {cells['labellar']}; {cells['leg']} | {o['mn9_labellar_mean_hz']:.1f} | "
                       f"{'yes' if o['mn9_responds'] else 'no'} | {'yes' if o['candidate'] else 'no'} |")
    cand = [a for a in PREFERENCE if out["arms"].get(a, {}).get("candidate")]
    out["decision"] = dict(candidates=cand, chosen=cand[0] if cand else None)
    L += ["## Summary and decision (prereg/05 section 5)", ""] + summary + [""]
    L.append("- Arms qualifying as candidate (preference R3 > N_v2 > N_v3): "
             + (", ".join(cand) + f"; the preferred is **{cand[0]}**." if cand else
                "**none**: stop and report; no further route or F2 test without a new pre-registration and the "
                "project owner's decision."))
    L.append("")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.with_suffix(".json").write_text(json.dumps(out, indent=1))
    OUT.with_suffix(".md").write_text("\n".join(L))
    print("\n".join(L))


if __name__ == "__main__":
    raise SystemExit(main())

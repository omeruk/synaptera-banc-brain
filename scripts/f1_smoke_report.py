"""Render docs/results/f1_banc_smoke.md from runs/f1/smoke.json and runs/f1/smoke_diag.json (numbers by script)."""
import json
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parent.parent
smoke = json.loads((ROOT / "runs/f1/smoke.json").read_text())
diag = json.loads((ROOT / "runs/f1/smoke_diag.json").read_text())
ref = json.loads((ROOT / "runs/bisect/openloop_new.json").read_text()) if (ROOT / "runs/bisect/openloop_new.json").exists() else None
b, f = diag["banc"], diag["flywire"]
qa = json.loads((ROOT / "docs/results/f1_banc_qa.json").read_text())["counts"]
if "n_pairs" not in smoke:     # first F1 run: the key n_synapses held the number of neuron pairs (Brian2 Synapses objects)
    smoke["n_pairs"], smoke["n_synapses"] = smoke["n_synapses"], qa["synapses"]
fo = json.loads((ROOT / "docs/results/f1_banc_qa.json").read_text())["sparseness"]["flywire_over_banc"]
ge5_path = ROOT / "runs/f1/smoke_ge5.json"
ge5 = json.loads(ge5_path.read_text()) if ge5_path.exists() else None
L = ["# F1 open-loop smoke run on BANC (reference Shiu parameters, w_syn unchanged)", "",
     "Generated by `scripts/f1_banc_smoke.py` + `scripts/f1_banc_smoke_diag.py` + `scripts/f1_smoke_report.py`. "
     "Reference sign rule (`prereg/01_banc_sign_rule.md`), no variant, no parameter changed. Drive: sugar GRNs "
     "(Function contains `sugar`, sensory / sensory_ascending; labellar = body part labellum, leg = front / middle / "
     "hind leg) at 100 Hz for 1 s in 25 ms steps, then all inputs cut for 200 ms; 3 seeds; Brian2 reference LIF.", "",
     f"Network: {smoke['n_neurons']:,} neurons, {smoke['n_synapses']:,} synapses in {smoke['n_pairs']:,} neuron pairs; driven: labellar "
     f"{smoke['groups']['labellar']}, leg {smoke['groups']['leg']}; MN9 {smoke['groups']['mn9']}. Setup "
     f"{smoke['setup_s']:.0f} s, total wall {smoke['total_wall_s']:.0f} s for {len(smoke['runs'])} runs, "
     f"peak RAM {smoke['peak_rss_gb']:.2f} GB.", "",
     "| condition | seeds | MN9 rate (Hz) | network rate (Hz) | DN rate (Hz) | driven GRN rate (Hz) | network, last 100 ms of the cut (Hz) |",
     "|---|---|---|---|---|---|---|"]
for c in ("labellar", "leg", "both", "none"):
    r = [x for x in smoke["runs"] if x["condition"] == c]
    inp = [x["input_rate_hz"] for x in r if x["input_rate_hz"] is not None]
    L.append(f"| {c} | {len(r)} | {np.mean([x['mn9_rate_hz'] for x in r]):.2f} | "
             f"{np.mean([x['network_rate_hz'] for x in r]):.3f} | {np.mean([x['dn_rate_hz'] for x in r]):.3f} | "
             f"{(f'{np.mean(inp):.1f}' if inp else '-')} | {np.mean([x['cut_last_100ms_hz'] for x in r]):.3f} |")
L += ["", "## Result", "",
      "**MN9 is silent (0.00 Hz in every condition and seed) and nothing runs away** (no residual activity after the "
      "cut). The network rate equals the rate of the driven GRNs themselves plus a small spread. By the stop rule of the "
      "F1 task nothing was recalibrated: any change of `w_syn` for BANC is a pre-registered F2 decision.", ""]
if ref:
    L += [f"Reference, FlyWire v783 with the same protocol (sugar 100 Hz, 1 s; `runs/bisect/openloop_new.json`): MN9 "
          f"{ref['mean']['mn9_rate_hz']:.1f} Hz, network {ref['mean']['net_rate_hz']:.3f} Hz.", ""]
e = b["engine_both_1s"]
L += ["## Why (read-only diagnostic, `smoke_diag.json`)",
      f"- MN9 is {b['mn9_hops_from_labellar']} hops from the labellar sugar GRNs and {b['mn9_hops_from_leg']} hops from "
      f"the leg sugar GRNs (FlyWire: {f['mn9_hops']} from the Shiu LB3 GRNs): the path exists.",
      f"- MN9 input synapses: BANC {b['mn9_input_synapses']}, FlyWire {f['mn9_input_synapses']} "
      f"({f['mn9_input_synapses'][0] / b['mn9_input_synapses'][0]:.1f}x and "
      f"{f['mn9_input_synapses'][1] / b['mn9_input_synapses'][1]:.1f}x more in FlyWire), consistent with the sparseness "
      "of `f1_banc_qa.md` section 3.",
      f"- Spread of activity (both groups, seed 0, 1 s): {e['driven_neurons']} driven neurons at "
      f"{e['driven_mean_rate_hz']:.0f} Hz; {e['other_neurons_spiking']} other neurons spike "
      f"({e['other_spikes']} spikes), by hop distance {e['other_spiking_by_hop']}; MN9 spikes {e['mn9_spikes']}. "
      "The activity dies out after hop 3: propagation is sub-threshold, consistent with a graph "
      f"sparser than the one `w_syn` was set on (`f1_banc_qa.md` section 3: FlyWire has {fo['in_syn_all_pairs']:.1f}x the "
      f"in-synapses per neuron on the graphs as run).",
      "", "## Consequence",
      "The registered open-loop tests of F2 (sugar -> MN9, tarsal GRN -> MN9) are expected not to pass on BANC with the unchanged "
      "reference parameters. The decision (input normalisation / `w_syn` scaling as a named model variant, or "
      "another route) belongs to a pre-registration, with the criterion fixed from open-loop physiology only "
      "(CLAUDE.md rule 3), before any BANC closed-loop run.", ""]
if ge5:
    L += ["", "## Sensitivity: the same protocol on the graph thresholded at >= 5 synapses per pair", "",
          f"`--min-syn 5` (`runs/f1/smoke_ge5.json`): {ge5['graph']['pairs_kept']:,} of "
          f"{ge5['graph']['pairs_before_threshold']:,} pairs kept ({ge5['graph']['synapses_kept']:,} synapses). "
          "This is *not* the reference arm: the Shiu FlyWire graph is not thresholded (min 1 synapse per pair), so "
          "the matched graph for the reference arm is the BANC export as it is (min 3).", "",
          "| condition | seeds | MN9 rate (Hz) | network rate (Hz) | network, last 100 ms of the cut (Hz) |",
          "|---|---|---|---|---|"]
    for c in ("labellar", "leg", "both", "none"):
        r = [x for x in ge5["runs"] if x["condition"] == c]
        L.append(f"| {c} | {len(r)} | {np.mean([x['mn9_rate_hz'] for x in r]):.2f} | "
                 f"{np.mean([x['network_rate_hz'] for x in r]):.3f} | "
                 f"{np.mean([x['cut_last_100ms_hz'] for x in r]):.3f} |")
    L.append("")
(ROOT / "docs/results/f1_banc_smoke.md").write_text("\n".join(L))
print("\n".join(L))

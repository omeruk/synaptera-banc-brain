"""Report of F5 step 2a-2 (prereg/16): reachability of the 12.5 deg turn amplitude.

    env -u PYTHONPATH python scripts/f5_reach_report.py      # writes docs/results/f5_reachability.{json,md}

Input: runs/f5/reach/ (`scripts/f5_reach_run.py`). Refuses to overwrite without --overwrite.
"""
import argparse
import hashlib
import json
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parent.parent
REC = ROOT / "runs" / "f5" / "reach"
OUT_JSON = ROOT / "docs" / "results" / "f5_reachability.json"
OUT_MD = ROOT / "docs" / "results" / "f5_reachability.md"
PARTS = ("true_I1", "true_I2", "shuffled_I1", "shuffled_I2")
A_MAX = 12.5
STATS = ("reach", "min_D", "frac_ge_target", "frac_ge_half", "max_abs_dA")


def build():
    setup = json.loads((REC / "setup.json").read_text())
    o = dict(prereg="prereg/16_f5_reachability.md", a_max_deg=A_MAX, scale_deg_per_unit=39.5,
             needed_sum=A_MAX / 39.5, trivial_bound_deg=39.5 * 16,
             record_sha256={f: hashlib.sha256((REC / f).read_bytes()).hexdigest()
                            for f in ("setup.json", "linear.json") + tuple(f"{p}.json" for p in PARTS)},
             setup={k: setup[k] for k in ("graph_sha256", "n_neurons", "n_edges", "n_inputs", "readout", "sigma",
                                          "i1_drives", "brain_model")},
             n_i2_records=len(setup["i2_records_sha256"]),
             bridge=dict(n_units=setup["bridge"]["n_units"], n_targets=setup["bridge"]["n_targets"]),
             shuffle={k: setup["shuffle"][k] for k in ("seed", "factor", "accepted", "tried", "rejected", "wall_s", "check")})
    parts = {}
    for p in PARTS:
        d = json.loads((REC / f"{p}.json").read_text())
        x = dict(n_trials=d["n_trials"], window=d["window"], graph_sha256=d["graph_sha256"])
        for P in ("P0", "P1", "P2"):
            x[P] = {k: d[P][k] for k in STATS}
        x["P2_evals"] = [{k: e[k] for k in ("step",) + STATS} for e in d["P2"]["evals"]]
        x["P2_not_converged"] = d["P2"]["not_converged"]
        x["P2_gains"] = d["P2"]["gains"]
        x["P2_leaks"] = d["P2"]["leaks"]
        x["step_s_mean"] = d["step_s_mean"]
        x["step_s_median"] = float(np.median(d["step_s"]))
        x["n_steps"] = len(d["step_s"])
        x["threads"] = d["threads"]
        x["best"] = max(x[P]["reach"] for P in ("P0", "P1", "P2"))
        x["reachable"] = bool(x["best"] >= A_MAX)
        x["half_reachable"] = bool(x["best"] >= A_MAX / 2)
        # post-hoc (not the registered rule, which takes the last evaluation): the best registered evaluation
        be = max(x["P2_evals"], key=lambda e: e["reach"])
        x["posthoc_best_eval"] = dict(step=be["step"], reach=be["reach"], min_D=be["min_D"],
                                      frac_ge_target=be["frac_ge_target"], max_abs_dA=be["max_abs_dA"])
        parts[p] = x
    o["parts"] = parts
    o["linear"] = json.loads((REC / "linear.json").read_text())
    o["true_I2_reachable"] = parts["true_I2"]["reachable"]
    return o


def fmt(v):
    return f"{v:.2f}"


def render(o):
    L = ["# F5 step 2a-2: can the bounded rate VNC reach 12.5 deg? (prereg/16)", ""]
    L.append("Generated by `scripts/f5_reach_run.py` and `scripts/f5_reach_report.py` from `runs/f5/reach/` (not "
             "committed). Procedures, inputs and the search are those of the committed prereg/16. Training-seed data "
             "only; nothing was tuned; prereg/14 is unchanged.")
    L.append("")
    L.append("## 1. What is measured")
    L.append("")
    L.append(f"- dA = 39.5 deg x sum_m sigma_m (s_mL - s_mR) over the 16 Lindsay `lateral` MNs (one neuron per type "
             f"and side). 12.5 deg needs sum = {o['needed_sum']:.3f}; the trivial bound |s| < 1 gives "
             f"|dA| < {o['trivial_bound_deg']:.0f} deg.")
    L.append("- D = window mean of c x dA per trial (c = intended direction); reach = mean D over the trials. "
             "Reachable if any procedure reaches >= 12.5 deg.")
    L.append(f"- I1: F3a-3 drives {', '.join(o['setup']['i1_drives'])} on the DNg02 baseline; 200 intervals, window "
             f"100-199. I2: {o['n_i2_records']} recorded FlyWire DN records at 60 deg/s (rot_left / rot_right, data "
             f"seeds 0-39) through the `ensemble` bridge ({o['bridge']['n_units']} units, {o['bridge']['n_targets']} "
             "BANC targets); 300 intervals, window 120-299. The prereg/14 target at 60 deg/s is 6.25 deg.")
    s = o["shuffle"]
    L.append(f"- `shuffled`: seed {s['seed']}, {s['accepted']:,} accepted swaps of {s['tried']:,} tried "
             f"(rejected: self-loop {s['rejected']['self_loop']:,}, duplicate {s['rejected']['duplicate']:,}, same edge "
             f"{s['rejected']['same_edge']}), {s['wall_s']:.0f} s. Check: degrees equal "
             f"{s['check']['in_degree_equal'] and s['check']['out_degree_equal']}, signs per presynaptic neuron equal "
             f"{s['check']['sign_per_pre_equal']}, no self-loops {s['check']['no_self_loops']}, no duplicates "
             f"{s['check']['no_duplicates']}; edges in place {100 * s['check']['fraction_in_place']:.3f} %, pairs kept "
             f"{100 * s['check']['fraction_pairs_kept']:.2f} %.")
    L.append("")
    L.append("## 2. Results (deg)")
    L.append("")
    L.append("P0 untrained (gain 1, leak 0.25); P1 every gain = G_MAX = 2; P2 gradient ascent on the directed dA "
             "within the bounds (Adam, lr 0.05, 200 steps).")
    L.append("")
    L.append("| graph | input | procedure | reach | min D | trials >= 12.5 | trials >= 6.25 | max per-interval abs dA |")
    L.append("|---|---|---|---|---|---|---|---|")
    for p, x in o["parts"].items():
        g, i = p.split("_")
        for P in ("P0", "P1", "P2"):
            v = x[P]
            L.append(f"| {g} | {i} | {P} | {fmt(v['reach'])} | {fmt(v['min_D'])} | {100 * v['frac_ge_target']:.0f} % | "
                     f"{100 * v['frac_ge_half']:.0f} % | {fmt(v['max_abs_dA'])} |")
    L.append("")
    L.append("| graph | input | best reach | 12.5 deg reached | 6.25 deg reached | P2 not converged | P2 gains min / max | "
             "gains > 1.9 | gains < 0.1 | leaks min / max |")
    L.append("|---|---|---|---|---|---|---|---|---|---|")
    for p, x in o["parts"].items():
        g, i = p.split("_")
        gn, lk = x["P2_gains"], x["P2_leaks"]
        L.append(f"| {g} | {i} | {fmt(x['best'])} | {'yes' if x['reachable'] else 'no'} | "
                 f"{'yes' if x['half_reachable'] else 'no'} | {'yes' if x['P2_not_converged'] else 'no'} | "
                 f"{gn['min']:.3f} / {gn['max']:.3f} | {100 * gn['frac_above_1_9']:.1f} % | "
                 f"{100 * gn['frac_below_0_1']:.1f} % | {lk['min']:.3f} / {lk['max']:.3f} |")
    L.append("")
    L.append("P2 reach on all trials of the set every 50 steps:")
    L.append("")
    L.append("| graph | input | " + " | ".join(f"step {e['step']}" for e in o["parts"]["true_I1"]["P2_evals"]) + " |")
    L.append("|---|---|" + "---|" * len(o["parts"]["true_I1"]["P2_evals"]))
    for p, x in o["parts"].items():
        g, i = p.split("_")
        L.append(f"| {g} | {i} | " + " | ".join(fmt(e["reach"]) for e in x["P2_evals"]) + " |")
    L.append("")
    L.append("## 3. Time per gradient step (measured; batch 8, float32, full BPTT, CPU)")
    L.append("")
    L.append("| graph | input | intervals | steps | mean (s) | median (s) | threads |")
    L.append("|---|---|---|---|---|---|---|")
    for p, x in o["parts"].items():
        g, i = p.split("_")
        L.append(f"| {g} | {i} | {300 if i == 'I2' else 200} | {x['n_steps']} | {x['step_s_mean']:.1f} | "
                 f"{x['step_s_median']:.1f} | {x['threads']} |")
    L.append("")
    L.append("## 4. mlp and linear arms")
    L.append("")
    lin = o["linear"]
    L.append("Their 16 MN outputs are unbounded linear outputs (no tanh, no gain bound): dA is linear in the linear "
             "arm's weights and scales with the mlp's output-layer weights, so any amplitude is reachable by scaling. "
             f"Illustration on I2: one least-squares linear map ({lin['n_features']} features: the bridge units through "
             "the 10 / 25 / 50 / 100 ms filters, plus a constant) fitted to the directed +-12.5 deg target:")
    L.append("")
    L.append("| weights | reach | min D | trials >= 12.5 | trials >= 6.25 | max abs dA |")
    L.append("|---|---|---|---|---|---|")
    for k in ("1", "2", "10"):
        v = lin[f"scale_{k}"]
        L.append(f"| x{k} | {fmt(v['reach'])} | {fmt(v['min_D'])} | {100 * v['frac_ge_target']:.0f} % | "
                 f"{100 * v['frac_ge_half']:.0f} % | {fmt(v['max_abs_dA'])} |")
    L.append("")
    L.append("## 5. Reading")
    L.append("")
    L.append("### 5.1 Registered verdict (prereg/16 section 1: best of P0, P1 and the last P2 evaluation)")
    L.append("")
    for p, x in o["parts"].items():
        g, i = p.split("_")
        L.append(f"- `{g}` on {i}: best reach {fmt(x['best'])} deg; 12.5 deg "
                 f"**{'reached' if x['reachable'] else 'not reached by the registered search'}**.")
    L.append("- mlp and linear: no such limit (section 4).")
    L.append("")
    L.append("### 5.2 Post-hoc (not registered; it does not change 5.1)")
    L.append("")
    L.append("The registered rule reports the last P2 evaluation. The P2 evaluations every 50 steps are on all trials "
             "of the set and are part of the registered schedule; their best is:")
    L.append("")
    L.append("| graph | input | step | reach | min D | trials >= 12.5 | max abs dA |")
    L.append("|---|---|---|---|---|---|---|")
    for p, x in o["parts"].items():
        g, i = p.split("_")
        b = x["posthoc_best_eval"]
        L.append(f"| {g} | {i} | {b['step']} | {fmt(b['reach'])} | {fmt(b['min_D'])} | "
                 f"{100 * b['frac_ge_target']:.0f} % | {fmt(b['max_abs_dA'])} |")
    L.append("")
    t2 = o["parts"]["true_I2"]
    b = t2["posthoc_best_eval"]
    l2 = t2["P2_evals"][-1]
    L.append(f"- For `true` on I2 the last evaluation (step {l2['step']}, reach {fmt(l2['reach'])} deg) is below "
             f"12.5 deg because the search became unstable: its smallest D is {fmt(l2['min_D'])} deg, i.e. some trials "
             f"turn hard the wrong way, and {100 * l2['frac_ge_target']:.0f} % of trials are >= 12.5 deg. At step "
             f"{b['step']} the parameters (inside the prereg/14 bounds) gave a reach of {fmt(b['reach'])} deg with "
             f"every trial >= 12.5 deg in the intended direction (smallest D {fmt(b['min_D'])} deg). So a bounded "
             "parameter set that reaches 12.5 deg on all 80 recorded trials exists; the amplitude is not capped "
             "below 12.5 deg.")
    L.append(f"- Raising every gain to G_MAX (P1) gives only {fmt(o['parts']['true_I1']['P1']['reach'])} / "
             f"{fmt(t2['P1']['reach'])} deg (I1 / I2): the amplitude comes from selective gains (after P2 about "
             f"{100 * t2['P2_gains']['frac_above_1_9']:.0f} % of gains are above 1.9 and "
             f"{100 * t2['P2_gains']['frac_below_0_1']:.0f} % below 0.1) and recurrent amplification, not from a "
             "uniform scale.")
    L.append("- The search reaches far beyond the target (hundreds of degrees, near the |s| -> 1 saturation of the "
             "readout MNs). The open risk for training is therefore not a ceiling but the start: the untrained output is "
             f"{fmt(t2['P0']['reach'])} deg on I2, and the ascent passed through unstable, latched states.")
    L.append("- The `ensemble` bridge has 225 units (221 by exact type, 4 by family; prereg/10, prereg/11). prereg/14 "
             "and docs/10 write 224, which is the unit count of the derangement bridges. prereg/14 is not edited; this "
             "is recorded here.")
    L.append("")
    L.append("### 5.3 Options (prereg/16 section 6: listed because the registered verdict for `true` on I2 is "
             "'not reached'; none is applied, prereg/14 is unchanged)")
    L.append("")
    L.append("| option | pros | cons |")
    L.append("|---|---|---|")
    L.append("| keep prereg/14 as is | 5.2 shows bounded parameters that reach the target on all trials; no change to "
             f"the registered model | training starts at {100 * t2['P0']['reach'] / A_MAX:.0f} % of the 12.5 deg "
             "target (I2); the ascent passed through unstable states, so a training run may be slow or unstable |")
    L.append("| one trainable readout scale k (dA = k x G1 x R_OUT x sum), shared rule for every arm | removes the "
             "start-scale gap directly; one parameter; same for all arms, so the comparison stays fair | a free output "
             "gain is a fitted (`F`) constant on the readout that docs/08 fixed; it can absorb part of what the network "
             "should learn; mlp / linear already have an equivalent freedom |")
    L.append("| larger G_MAX (for example 5 or 10) | more headroom per edge; no new parameter type | changes a "
             "registered bound; makes runaway recurrent excitation easier (more instability); still a uniform rule that "
             "does not address the start scale |")
    L.append("| input scaling (smaller R_IN, i.e. larger clamp per Hz) | larger DN drive into the VNC from the start | "
             "changes the registered rate scale; pushes the clamped DNs out of (0, 1) at high rates; affects stage B/C "
             "consistency with the bridge |")
    L.append("| initialise theta from a short P2-like warm-up | — | uses the objective before training: not acceptable "
             "as a model change, listed only to be excluded |")
    L.append("")
    return "\n".join(L)


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--overwrite", action="store_true")
    a = ap.parse_args(argv)
    if (OUT_JSON.exists() or OUT_MD.exists()) and not a.overwrite:
        raise SystemExit("report exists (use --overwrite)")
    o = build()
    OUT_JSON.write_text(json.dumps(o, indent=1))
    OUT_MD.write_text(render(json.loads(OUT_JSON.read_text())))
    print({p: (round(x["best"], 3), x["reachable"]) for p, x in o["parts"].items()})
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
